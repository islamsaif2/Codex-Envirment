import fs from "node:fs";
import vm from "node:vm";
const file="worker.mjs";
let worker=fs.readFileSync(file,"utf8");
const embedded=worker.match(/const APP_HTML_B64 = "([^"]+)"/);
if(!embedded)throw Error("Overview compact V2: embedded HTML missing");
let html=Buffer.from(embedded[1],"base64").toString("utf8");
const css=fs.readFileSync("overview-compact-v2.css","utf8");
const js=fs.readFileSync("overview-compact-v2.js","utf8");
new vm.Script(js,{filename:"overview-compact-v2.js"});
if(!html.includes("</head>")||!html.includes("</body>"))throw Error("Overview compact V2: insertion anchors missing");
if(!html.includes('id="page-title"')||!html.includes('id="content"'))throw Error("Overview compact V2: expected layout not found");
if(!html.includes('dashboard-date-compare'))throw Error("Overview compact V2: existing date control missing");
html=html.replace("</head>",'<style id="ultra-compact-overview-v2">'+css+"</style></head>");
html=html.replace("</body>","<script>\n"+js+"\n</script>\n</body>");
for(const [i,tag] of [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/gi)].entries())if(tag[1].trim())new vm.Script(tag[1],{filename:"compact-overview-inline-"+i});
worker=worker.replace(embedded[1],Buffer.from(html,"utf8").toString("base64"));
fs.writeFileSync(file,worker);
console.log("Overview V2 compact layout installed with existing metric descriptions preserved.");
